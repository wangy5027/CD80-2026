import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_DIR || 'playwright');
const output = 'data/skill-availability-browser';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:48995/desktop/');
  await page.getByRole('button', { name: '创建账号', exact: true }).click();
  await page.locator('input[name="name"]').fill('选择状态测试');
  await page.locator('input[name="email"]').fill(`skill-${Date.now()}@example.invalid`);
  await page.locator('input[name="password"]').fill('fixture-password');
  await page.locator('form button[type="submit"]').click();
  await page.getByRole('button', { name: '扩展', exact: true }).click();
  await page.getByLabel('能力目录').selectOption('public');
  await page.locator('.cap-card').filter({ hasText: '资料摘要方法' }).click();
  await page.getByRole('button', { name: '保存个人副本', exact: true }).click();
  await page.getByRole('button', { name: '试试这个示例', exact: true }).click();
  await page.getByRole('button', { name: '开始验证', exact: true }).click();
  // This is a deterministic UI fixture, not a real-model quality assessment.
  await page.getByRole('button', { name: '确认符合预期', exact: true }).click();
  await page.getByText('已确认验证结果，可以启用此版本。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '新任务', exact: true }).first().click();
  await page.getByLabel('输入消息').fill('保留这段草稿');
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Skill', exact: true }).click();
  const option = page.locator('.extension-option').filter({ hasText: '资料摘要方法' });
  await option.waitFor();
  assert.equal(await option.isDisabled(), true);
  assert.match(await option.innerText(), /已验证，尚未启用/);
  assert.match(await page.locator('.extension-reason').innerText(), /点击“启用此版本”/);
  await page.screenshot({ path: `${output}/verified-not-enabled.png`, fullPage: true });
  await page.getByRole('button', { name: '去扩展处理 资料摘要方法', exact: true }).click();
  await page.locator('.cap-detail h2').filter({ hasText: '资料摘要方法' }).waitFor();
  await page.getByRole('button', { name: '启用并用于对话', exact: true }).click();
  assert.equal(await page.getByLabel('输入消息').inputValue(), '保留这段草稿');
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Skill', exact: true }).click();
  await page.getByText('本轮已选择，无需重复添加；可在输入框上方移除。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '移除 资料摘要方法', exact: true }).click();
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Skill', exact: true }).click();
  await option.click();
  assert.ok(await page.getByRole('button', { name: '移除 资料摘要方法', exact: true }).isVisible());
  assert.deepEqual(errors, []);
  await writeFile(`${output}/report.json`, JSON.stringify({ passed: true, model: 'fixture', pageErrors: errors, checks: ['verified but disabled reason', 'direct link to exact asset', 'enable and select', 'draft preserved', 'already selected reason', 'remove and reselect'] }, null, 2));
} finally { await browser.close(); }
