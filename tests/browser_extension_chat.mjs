import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_DIR || 'playwright');
const output = 'data/extension-chat-browser';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:48995/desktop/');
  await page.getByRole('button', { name: '创建账号', exact: true }).click();
  await page.locator('input[name="name"]').fill('扩展接入测试');
  await page.locator('input[name="email"]').fill(`extension-${Date.now()}@example.invalid`);
  await page.locator('input[name="password"]').fill('fixture-password');
  await page.locator('form button[type="submit"]').click();
  await page.getByRole('button', { name: '扩展', exact: true }).click();
  await page.getByRole('tab', { name: /Tools/ }).click();
  await page.getByLabel('能力目录').selectOption('public');
  await page.locator('.cap-card').filter({ hasText: '十进制求和' }).click();
  await page.getByRole('region', { name: '如何使用' }).waitFor();
  assert.match(await page.locator('.cap-guide').innerText(), /0.30/);
  await page.getByRole('button', { name: '保存个人副本', exact: true }).click();
  await page.getByRole('button', { name: '试试这个示例', exact: true }).click();
  assert.equal(await page.getByLabel('数字 1', { exact: true }).inputValue(), '0.10');
  assert.equal(await page.getByLabel('数字 2', { exact: true }).inputValue(), '0.20');
  assert.equal(await page.getByLabel('求和结果', { exact: true }).inputValue(), '0.30');
  await page.getByRole('button', { name: '开始验证', exact: true }).click();
  await page.getByText('样例验证通过。请明确启用此版本。', { exact: true }).waitFor();
  await page.getByRole('button', { name: '启用并用于对话', exact: true }).click();
  await page.getByRole('button', { name: '移除 十进制求和', exact: true }).click();
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Tool', exact: true }).click();
  await page.locator('.extension-options button').filter({ hasText: '十进制求和' }).click();
  await page.getByLabel('输入消息').fill('请调用十进制求和工具，计算0.10与0.20。');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.locator('.message.assistant').filter({ hasText: '合计 0.30' }).waitFor();
  await page.locator('.stop-bar').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: '移除 十进制求和', exact: true }).count(), 0);
  // Second turn has no explicit references: the graph discovers it itself.
  await page.getByLabel('输入消息').fill('请再次调用十进制求和工具，计算0.10与0.20。');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.message.assistant')].filter(e => e.textContent.includes('合计 0.30')).length === 2);
  await page.locator('.stop-bar').waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Application', exact: true }).click();
  await page.locator('.extension-options button').first().click();
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.getByRole('dialog', { name: '确认应用参数' }).waitFor();
  assert.ok(await page.getByRole('button', { name: '确认参数并运行应用' }).isVisible());
  await page.screenshot({ path: `${output}/application-input.png`, fullPage: true });
  const dialog = page.getByRole('dialog', { name: '确认应用参数' });
  await dialog.getByRole('button', { name: '确认参数并运行应用' }).click();
  await dialog.locator('.agent-error').waitFor(); // missing input must not run
  const chooser = page.waitForEvent('filechooser');
  await dialog.getByRole('button', { name: '上传新文件' }).click();
  await (await chooser).setFiles({ name: 'extension-summary.csv', mimeType: 'text/csv', buffer: Buffer.from('group,amount\nA,0.10\nA,0.20\n') });
  await page.waitForFunction(() => Boolean(document.querySelector('.agent-input-form select')?.value));
  await dialog.locator('.form-field').filter({ hasText: '分组列' }).locator('input').fill('group');
  await dialog.locator('.form-field').filter({ hasText: '求和列' }).locator('input').fill('amount');
  const invocation = page.waitForRequest(r => r.url().endsWith('/agent-runs') && r.method() === 'POST');
  await dialog.getByRole('button', { name: '确认参数并运行应用' }).click();
  assert.equal((await invocation).postDataJSON().mode, 'invoke');
  await dialog.waitFor({ state: 'hidden' });
  await page.locator('.agent-status.succeeded').first().waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sidebar')).visibility === 'hidden');
  await page.getByRole('button', { name: '添加文件或扩展' }).click();
  await page.getByRole('button', { name: '选择 Tool', exact: true }).click();
  await page.locator('.extension-options button').first().waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: `${output}/mobile-picker.png`, fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(`${output}/report.json`, JSON.stringify({ passed: true, pageErrors: errors, model: 'fixture', wasi: 'real', checks: ['public guide', 'fill example without execution', 'validate and enable', 'plus selection', 'selection cleared after send', 'automatic discovery on next turn', 'application missing-input validation', 'application upload field assignment', 'application actual execution', 'mobile overflow'] }, null, 2));
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png`, fullPage: true });
  const runs = await (await page.request.get('http://127.0.0.1:48995/desktop/api/agent-runs')).json();
  console.error(JSON.stringify((runs.runs || []).map(r => ({ status: r.status, error: r.error, approvals: r.approvals?.map(a => ({ kind: a.kind, status: a.status })) }))));
  throw error;
} finally { await browser.close(); }
