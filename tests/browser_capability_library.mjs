import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_DIR || 'playwright');
const output = path.resolve('data/capability-browser');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.BROWSER_CHANNEL || 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:48995/desktop/');
  await page.getByRole('button', { name: '创建账号', exact: true }).click();
  const form = page.locator('form');
  await form.locator('input[name="name"]').fill('能力库测试');
  await form.locator('input[name="email"]').fill(`library-ui-${Date.now()}@example.invalid`);
  await form.locator('input[name="password"]').fill('fixture-password');
  await form.locator('button[type="submit"]').click();
  await page.getByRole('button', { name: '扩展', exact: true }).click();
  await page.getByRole('tab', { name: /Tools/ }).click();
  await page.getByRole('combobox', { name: '能力目录' }).selectOption('public');
  await page.locator('.cap-card').filter({ hasText: '十进制求和' }).click();
  await page.getByRole('button', { name: '保存个人副本', exact: true }).click();
  await page.getByRole('button', { name: '试试这个示例', exact: true }).click();
  await page.getByRole('button', { name: '开始验证', exact: true }).click();
  await page.getByText('样例验证通过。请明确启用此版本。', { exact: true }).waitFor();
  await page.getByText('更多操作', { exact: true }).click();
  await page.getByRole('button', { name: '启用此版本', exact: true }).click();
  await page.getByLabel('自由试用', { exact: true }).check();
  await page.getByRole('button', { name: '运行试用', exact: true }).click();
  await page.getByText('运行成功，尚未确认结果符合预期。自由试用不会启用能力或生成验证通过记录。', { exact: true }).waitFor();
  assert.match(await page.locator('.cap-result').innerText(), /0.30/);
  await page.locator('section.page').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '用于对话', exact: true }).click();
  await page.locator('textarea').first().fill('请调用求和工具');
  await page.getByRole('button', { name: '发送消息', exact: true }).click();
  await page.locator('.message.assistant').filter({ hasText: '合计 0.30' }).waitFor();
  await page.locator('.stop-bar').waitFor({ state: 'hidden' });
  assert.match(await page.locator('.cap-message-trace').innerText(), /本次能力记录/);
  await page.getByRole('button', { name: '扩展', exact: true }).click();
  await page.getByRole('tab', { name: /Tools/ }).click();
  await page.locator('.cap-card').filter({ hasText: '十进制求和' }).click();
  await page.getByText('更多操作', { exact: true }).click();
  await page.getByRole('button', { name: '编辑草稿', exact: true }).click();
  const draft = JSON.parse(await page.getByLabel('能力草稿内容').inputValue());
  draft.description = '浏览器测试修改后的说明';
  await page.getByLabel('能力草稿内容').fill(JSON.stringify(draft));
  await page.getByRole('button', { name: '审阅并保存', exact: true }).click();
  await page.getByText('新内容已保存为版本，请重新验证。原版本保持不变。', { exact: true }).waitFor();
  await page.getByText('版本与技术信息', { exact: true }).click();
  assert.match(await page.getByLabel('查看版本').innerText(), /V2/);
  await page.getByRole('button', { name: '禁用', exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll('.cap-detail button')].find(e => e.textContent === '禁用')?.disabled);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.sidebar')).visibility === 'hidden');
  await page.locator('section.page').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true, animations: 'disabled' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, 'report.json'), JSON.stringify({ passed: true, checks: ['public copy','real WASI validation','enable','free trial','conversation invocation','immutable edit','disable','mobile overflow'], pageErrors: errors, model: 'fixture', runtime: 'real WASI' }, null, 2));
} catch (error) {
  await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
  throw error;
} finally { await browser.close(); }
