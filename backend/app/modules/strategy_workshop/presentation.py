"""Versioned audience instructions; presentation never changes execution rules."""
from .contracts import fail


LANGUAGE_STYLE_VERSION = "workshop-language-1.0.0"


def language_style(value="beginner"):
    if not isinstance(value, str) or value not in {"beginner", "expert"}:
        fail("语言风格请选择面向小白或面向专家。", field="languageStyle")
    return value


def style_text(style, beginner, expert):
    return expert if style == "expert" else beginner


